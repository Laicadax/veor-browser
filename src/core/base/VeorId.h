// A type-safe, zero-overhead identifier. Two StrongIds with different Tag types
// are incompatible at compile time, preventing accidental mixing of IDs.
//
// Thread safety: Trivially copyable. Safe to use from any thread.
// Memory layout: sizeof(uint64_t). No heap allocation.
// â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

template <typename Tag>
class StrongId {
 public:
  using ValueType = uint64_t;

  constexpr StrongId() noexcept : value_(0) {}
  explicit constexpr StrongId(ValueType value) noexcept : value_(value) {}

  // Access
  constexpr ValueType value() const noexcept { return value_; }
  constexpr bool IsValid() const noexcept { return value_ != 0; }

  // Comparison
  constexpr bool operator==(StrongId other) const noexcept {
    return value_ == other.value_;
  }
  constexpr bool operator!=(StrongId other) const noexcept {
    return value_ != other.value_;
  }
  constexpr bool operator<(StrongId other) const noexcept {
    return value_ < other.value_;
  }
  constexpr bool operator<=(StrongId other) const noexcept {
    return value_ <= other.value_;
  }
  constexpr bool operator>(StrongId other) const noexcept {
    return value_ > other.value_;
  }
  constexpr bool operator>=(StrongId other) const noexcept {
    return value_ >= other.value_;
  }

  // Hash support for unordered containers
  struct Hash {
    constexpr size_t operator()(StrongId id) const noexcept {
      return std::hash<ValueType>{}(id.value_);
    }
  };

  // Stream output (debugging)
  friend std::ostream& operator<<(std::ostream& os, StrongId id) {
    return os << static_cast<unsigned long long>(id.value_);
  }

 private:
  ValueType value_;
};

