// Thread-safe monotonic ID generator. Each process session starts from 1.

class IdGenerator {
 public:
  static uint64_t Next() noexcept;

  template <typename Tag>
  static StrongId<Tag> NextId() noexcept {
    return StrongId<Tag>(Next());
  }

 private:
  static std::atomic<uint64_t> counter_;
};

